r"""Digest of autoplay runs (dev-only): turns survey-*.jsonl and library.jsonl into a Markdown atlas per area.

    python -I tools/autoplay/report.py <run-dir>            # writes <run-dir>/atlas.md

Room contents come from three sources, labelled: the room files (items/enemies/doors in data/games/re1/room-index.json),
live memory after entering the room from a new game (enemy slots, HP), and a local vision model's one-line
description of a screenshot (unverified, for orientation only).
"""
from __future__ import annotations

import json
import sys
from collections import defaultdict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))

ROOT = Path(__file__).resolve().parents[2]
DATA = ROOT / "data" / "games" / "re1"


def load_jsonl(path: Path) -> list[dict]:
    return [json.loads(l) for l in path.read_text(encoding="utf-8").splitlines() if l.strip()] if path.exists() else []


def main(argv: list[str]) -> int:
    sys.stdout.reconfigure(encoding="utf-8")
    run = Path(argv[0])
    names = json.loads((DATA / "names.json").read_text(encoding="utf-8"))
    rooms = json.loads((DATA / "rooms.json").read_text(encoding="utf-8"))
    index = json.loads((DATA / "room-index.json").read_text(encoding="utf-8"))
    enemy = lambda t: names["enemies"].get(str(t), f"type {t}")  # noqa: E731
    item = lambda i: names["items"].get(str(i), f"item {i}")  # noqa: E731

    survey = {c: {e["room"]: e for e in load_jsonl(run / "survey" / f"survey-{c}.jsonl") or load_jsonl(run / f"survey-{c}.jsonl")}
              for c in ("jill", "chris")}
    library = load_jsonl(run / "library" / "library.jsonl") or load_jsonl(run / "library.jsonl")
    # Phase surveys (started from a practice save later in the story): survey-<character>-<phase>.jsonl
    phases: dict[tuple[str, str], dict[str, dict]] = {}
    for path in sorted((run / "survey").glob("survey-*-*.jsonl")):
        _, who, tag = path.stem.split("-", 2)
        phases[(who, tag)] = {e["room"]: e for e in load_jsonl(path)}

    lines = ["# Room atlas (automated run)", "",
             "Generated by tools/autoplay/report.py. *Files*: the game's room files (what can spawn). *Live*: memory "
             "after entering from a new game (story state early-game, so later-game rooms may differ). *Seen*: a local "
             "vision model's description — unverified.", ""]
    files: dict[str, dict[str, dict[str, list]]] = defaultdict(lambda: defaultdict(lambda: defaultdict(list)))
    for kind in ("items", "enemies", "doors"):
        for e in index[kind]:
            for who in (("jill", "chris") if e["player"] == "both" else (e["player"],)):
                files[e["room"]][who][kind].append(e)
    # Door targets whose room file is a 4-byte stub (the room exists only in the return-mansion stages) aren't rooms.
    import survey as survey_module  # tools/autoplay/survey.py
    all_rooms = sorted((set(survey["jill"]) | set(survey["chris"]) | set(files)), key=lambda r: (r[0], r[1:]))
    all_rooms = [r for r in all_rooms if survey_module.room_file_ok(r, "jill") or survey_module.room_file_ok(r, "chris")]
    by_area: dict[str, list[str]] = defaultdict(list)
    for r in all_rooms:
        by_area[rooms["rooms"].get(r, {}).get("area") or rooms["areas"].get(r[0], f"Stage {r[0]}")].append(r)

    totals = {c: (len(survey[c]), sum(1 for e in survey[c].values() if e.get("entered")),
                  sum(1 for e in survey[c].values() if e.get("control"))) for c in survey}
    lines += ["| Character | Rooms tried | Entered | Player in control after |", "|---|---|---|---|"]
    lines += [f"| {c.title()} | {t[0]} | {t[1]} | {t[2]} |" for c, t in totals.items()]
    lines.append("")

    for area, area_rooms in by_area.items():
        lines += [f"## {area}", ""]
        for r in area_rooms:
            info = rooms["rooms"].get(r, {})
            title = f"### {r}" + (f" — {info['name']}" if info.get("name") else "")
            lines += [title, ""]
            for c in ("jill", "chris"):
                f = files.get(r, {}).get(c, {})
                if f:
                    items = ", ".join(f"{item(i['item'])}×{i['quantity']}" if i["quantity"] > 1 else item(i["item"]) for i in f.get("items", []))
                    foes = ", ".join(sorted({enemy(e["type"]) for e in f.get("enemies", [])}))
                    exits = ", ".join(sorted({d["target"] for d in f.get("doors", [])}))
                    lines.append(f"- *Files ({c})*: items: {items or '—'}; enemies: {foes or '—'}; doors to: {exits or '—'}")
                runs = [("new game", survey[c].get(r))] + [(tag, rows.get(r)) for (who, tag), rows in phases.items() if who == c]
                for phase, e in runs:
                    if not e:
                        continue
                    where = f"{c}, {phase}"
                    if e.get("error"):
                        lines.append(f"- *Live ({where})*: not reached — {e['error'][-120:]}")
                    else:
                        live = ", ".join(f"{enemy(x['type'])} ({x['hp']} HP)" for x in e.get("enemies", [])) or "no active enemy slots"
                        lines.append(f"- *Live ({where})*: {live}; control {'yes' if e.get('control') else 'no'}; HP after {e.get('hp')}")
                        if e.get("seen"):
                            lines.append(f"- *Seen ({where})*: {e['seen'].replace(chr(10), ' ')[:220]}")
            lines.append("")

    if library:
        ok = sum(1 for e in library if e.get("roomMatches") and e.get("characterMatches"))
        lines += ["## Save library", "", f"{ok} of {len(library)} saves loaded with room and character matching the "
                  "offline decode.", "", "| Save | Expected | Live | Result |", "|---|---|---|---|"]
        for e in library:
            want = e.get("expected", {})
            live = e.get("live", {})
            result = "error: " + e["error"][-80:] if e.get("error") else (
                "OK" if e.get("roomMatches") and e.get("characterMatches") else "MISMATCH")
            lines.append(f"| {e['name']} | {want.get('room')} {want.get('character')} | {live.get('room')} {live.get('character')} | {result} |")
        lines.append("")

    (run / "atlas.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {run / 'atlas.md'} ({len(all_rooms)} rooms)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))

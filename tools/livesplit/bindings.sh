#!/usr/bin/env bash
# Regenerates src/Lockpick.LiveSplit/Generated/LiveSplitCore.cs from the pinned submodule (run after moving it).
# The features must match the native build in src/Lockpick.LiveSplit/Lockpick.LiveSplit.csproj.
set -euo pipefail
root="$(cd "$(dirname "$0")/../.." && pwd)"
out="$(mktemp -d)"
(cd "$root/extern/livesplit-core/capi/bind_gen" && cargo run --release -q -- --features software-rendering --output-dir "$out")
{
  echo "// <auto-generated>"
  echo "// Generated by livesplit-core's bind_gen (extern/livesplit-core/capi/bind_gen, features: default + software-rendering)."
  echo "// Regenerate with tools/livesplit/bindings.sh; don't edit by hand. livesplit-core is MIT or Apache-2.0."
  echo "// </auto-generated>"
  echo "#nullable disable"
  echo "#pragma warning disable"
  cat "$out/LiveSplitCore.cs"
} > "$root/src/Lockpick.LiveSplit/Generated/LiveSplitCore.cs"
rm -rf "$out"
echo "wrote src/Lockpick.LiveSplit/Generated/LiveSplitCore.cs"
